const { Paragraph, TextRun, Table, TableRow, TableCell, BorderStyle, WidthType, ShadingType } = require("docx");
const { h1, h2, h3, p, q, blank } = require("./method_part1.js");

const border = { style: BorderStyle.SINGLE, size: 1, color: "BBBBBB" };
const borders = { top: border, bottom: border, left: border, right: border };
const cm = { top: 50, bottom: 50, left: 100, right: 100 };
function cell(text, opts = {}) {
  const { bold = false, width = 2340, shading = undefined } = opts;
  return new TableCell({
    borders, width: { size: width, type: WidthType.DXA }, margins: cm,
    shading: shading ? { fill: shading, type: ShadingType.CLEAR } : undefined,
    children: [new Paragraph({ spacing: { line: 240, after: 0 }, children: [
      new TextRun({ text, bold, font: "Arial", size: 19 })
    ]})]
  });
}
function row2(a, b, opts = {}) {
  const { header = false } = opts;
  return new TableRow({ tableHeader: header, cantSplit: true, children: [
    cell(a, { bold: header, width: 2000, shading: header ? "E8E8E8" : undefined }),
    cell(b, { bold: header, width: 7360, shading: header ? "E8E8E8" : undefined }),
  ]});
}
function tbl2(rows) {
  return new Table({ width: { size: 9360, type: WidthType.DXA }, columnWidths: [2000, 7360], rows });
}
function tblN(header, rows, widths) {
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA }, columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((t, i) => cell(t, { bold: true, width: widths[i], shading: "E8E8E8" })) }),
      ...rows.map(r => new TableRow({ cantSplit: true, children: r.map((t, i) => cell(t, { width: widths[i] })) })),
    ]
  });
}

